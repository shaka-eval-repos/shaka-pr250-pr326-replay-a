module SeamInitializerPointerAssertions
  def write_foreign_readme(root)
    FileUtils.mkdir_p(File.join(root, '.agents'))
    path = File.join(root, '.agents/README.md')
    File.write(path, "owner: repository\n")
    path
  end

  def with_unreadable(path)
    File.chmod(0o000, path)
    yield
  ensure
    File.chmod(0o644, path)
  end

  def plant_legacy_readme(root)
    path = File.join(root, '.agents/README.md')
    original = "#{readme_marker_line}\nlegacy pointer from Shaka 0.0.1.pre.0\n"
    File.write(path, original)
    [path, original]
  end

  def readme_marker_line = "<!-- #{SeamInitializerTestHelpers::GENERATED_MARKER} -->"

  def assert_legacy_readme_report(error)
    assert_includes error, '.agents/README.md'
    assert_includes error, '.agents/shaka.md'
    assert_includes error, 'will not delete it'
  end

  def assert_pointer_file(path)
    pointer = File.read(path)

    assert_equal 0o644, File.stat(path).mode & 0o777
    assert_pointer_identity(pointer)
    assert_pointer_commands(pointer)
    pointer.scan(%r{https://github\.com/shakacode/shaka/blob/main/([^\s)]+)}).flatten.each do |target|
      assert_path_exists File.expand_path("../#{target}", __dir__)
    end
  end

  def assert_pointer_identity(pointer)
    assert_includes pointer, SeamInitializerTestHelpers::GENERATED_MARKER
    assert_includes pointer, "from Shaka #{Shaka::VERSION}"
    assert_includes pointer, Shaka::PRODUCT_STAGE
    assert_includes pointer, 'version: 1'
    refute_includes pointer, 'Shaka V2'
    refute_includes pointer, 'Shaka V1'
    assert_includes pointer, 'https://github.com/shakacode/shaka/blob/main/docs/settings.md'
  end

  def assert_pointer_commands(pointer)
    commands = pointer.scan(/`([^`]+)`/).flatten

    assert_includes commands, 'shaka seam check --root . --local'
    assert_includes commands, 'shaka seam check --root . --ref SHA'
    assert_includes commands, 'shaka seam pointer'
  end
end

