module SeamInitializerTestHelpers
  COMMAND = File.expand_path('../skills/shaka/scripts/shaka', __dir__)
  GENERATED_MARKER = 'Generated by shaka seam init.'
  CONTRACT = '.agents/shaka/config.yml'
  WRAPPERS = %w[.agents/shaka/bin/setup .agents/shaka/bin/validate .agents/shaka/bin/test].freeze
  GENERATED = [CONTRACT, '.agents/shaka.md', *WRAPPERS].freeze

  def with_repository(&)
    Dir.mktmpdir('shaka-seam-init') do |root|
      FileUtils.mkdir_p(File.join(root, 'bin'))
      %w[setup validate].each do |name|
        path = File.join(root, 'bin', name)
        File.write(path, "#!/bin/sh\nexit 0\n")
        File.chmod(0o755, path)
      end
      git!(root, 'init', '-q', '--initial-branch', 'main')
      yield root
    end
  end

  def init(root, setup_command: 'bin/setup', validate_command: 'bin/validate',
           test_command: 'bundle exec rake test')
    Open3.capture3(*init_arguments(root, setup_command:, validate_command:, test_command:))
  end

  def init_arguments(root, setup_command: 'bin/setup', validate_command: 'bin/validate',
                     test_command: 'bundle exec rake test')
    [COMMAND, 'seam', 'init', '--root', root, '--base-branch', 'main',
     '--setup-command', setup_command, '--validate-command', validate_command,
     '--test-command', test_command, '--review-policy', 'meaningful_changes',
     '--ci-review-job', 'claude-review']
  end

  def generated_files(root)
    GENERATED.map { |path| File.join(root, path) }
  end

  def wrapper_files(root)
    WRAPPERS.map { |path| File.join(root, path) }
  end

  def snapshot(root)
    generated_files(root).to_h { |path| [path, [File.read(path), File.stat(path).mode]] }
  end

  def assert_complete_seam(root, output)
    config = JSON.parse(output)
    assert_equal %w[main ask], [config.fetch('base_branch'), config.dig('merge', 'preference')]
    assert_equal %w[base_branch branches commands merge opening_check paths prose_limits review version wip],
                 config.keys.sort
    assert_equal({ 'preference' => 'ask', 'limits' => Shaka::MergeLimits::DEFAULTS }, config.fetch('merge'))
    assert_includes File.read(File.join(root, CONTRACT)), GENERATED_MARKER
    wrapper_files(root).each { |path| assert_generated_wrapper(path) }
  end

  def assert_generated_wrapper(path)
    assert File.executable?(path)
    assert_includes File.read(path), GENERATED_MARKER
  end

  def write_recorder(root)
    FileUtils.mkdir_p(File.join(root, 'bin'))
    File.write(File.join(root, 'bin/record.rb'), <<~RUBY)
      require 'json'
      File.write('arguments.json', JSON.generate(ARGV))
    RUBY
  end

  def assert_forwarded_arguments(root)
    runtime_argument = '; touch should-not-exist'
    command = File.join(root, '.agents/shaka/bin/test')
    _output, status = Open3.capture2e(command, 'space value', runtime_argument)
    recorded = JSON.parse(File.read(File.join(root, 'arguments.json')))
    assert_predicate status, :success?
    assert_equal ['configured', 'space value', runtime_argument], recorded
    refute_path_exists File.join(root, 'should-not-exist')
  end

  def write_foreign_test_wrapper(root)
    FileUtils.mkdir_p(File.join(root, '.agents/shaka/bin'))
    path = File.join(root, '.agents/shaka/bin/test')
    File.write(path, "#!/bin/sh\necho repository-owned\n")
    path
  end

  def with_external_executable
    Dir.mktmpdir('shaka-seam-outside') do |outside|
      path = File.join(outside, 'setup')
      File.write(path, "#!/bin/sh\n")
      File.chmod(0o755, path)
      yield path
    end
  end

  def with_noisy_git
    Dir.mktmpdir('shaka-fake-git') do |bin|
      git = File.join(bin, 'git')
      real = Open3.capture2('sh', '-c', 'command -v git').first.strip
      File.write(git, "#!/bin/sh\ncase \"$*\" in *--show-toplevel*) exec #{real} \"$@\" ;; esac\n" \
                      "printf 'main\\n'\nprintf 'warning\\n' >&2\n")
      File.chmod(0o755, git)
      yield({ 'PATH' => [bin, ENV.fetch('PATH', '')].join(File::PATH_SEPARATOR) })
    end
  end

  def git!(root, *)
    output, status = Open3.capture2e('git', '-C', root, *)
    raise output unless status.success?
  end

  def prepare_detached_previous_checkout(root)
    git!(root, 'add', '.')
    git!(root, '-c', 'user.name=Test', '-c', 'user.email=test@example.com', 'commit', '-m', 'initial')
    git!(root, 'switch', '--detach', 'HEAD')
    git!(root, 'switch', 'main')
  end
end

module SeamInitializerAssertions
  def assert_refuses_changed_mode(root, relative, mode)
    path = File.join(root, relative)
    File.chmod(mode, path)
    _output, error, status = init(root)
    refute_predicate status, :success?
    assert_includes error, "Refusing existing destination: #{relative}"
    assert_equal mode, File.stat(path).mode & 0o777
  end
end

class SeamInitializerTest < Minitest::Test
  include SeamInitializerTestHelpers
  include SeamInitializerAssertions

  def test_init_creates_and_validates_a_complete_repository_seam
    with_repository do |root|
      output, error, status = init(root)

      assert_predicate status, :success?, error
      assert_complete_seam(root, output)
      assert_equal '{login}-{host}/{issue}-{description}', JSON.parse(output).dig('branches', 'name')
    end
  end

  def test_generated_command_forwards_runtime_arguments_without_shell_interpretation
    with_repository do |root|
      write_recorder(root)
      _output, error, status = init(root, test_command: 'ruby bin/record.rb configured')
      assert_predicate status, :success?, error
      assert_forwarded_arguments(root)
    end
  end

  def test_repeat_init_is_idempotent
    with_repository do |root|
      assert_predicate init(root).last, :success?
      original = snapshot(root)

      output, error, status = init(root)

      assert_predicate status, :success?, error
      assert JSON.parse(output)
