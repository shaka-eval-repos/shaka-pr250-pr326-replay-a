# frozen_string_literal: true

require 'open3'
require 'yaml'
require_relative '../configuration'
require_relative '../configuration/wrapper_template'
require_relative 'initializer_destination'
require_relative 'initializer_input'
require_relative 'initializer_readme'

module Shaka
  class Seam
    # Creates the smallest complete repository seam without replacing repo-owned files.
    class Initializer
      MARKER = 'Generated by shaka seam init.'
      POINTER_PATH = Configuration::Paths::POINTER
      LAYOUT = Configuration::Layout::NEW
      GIT_ENVIRONMENT = %w[GIT_DIR GIT_WORK_TREE GIT_COMMON_DIR GIT_PREFIX GIT_CEILING_DIRECTORIES].freeze
      UPGRADE_GUIDE = 'https://github.com/shakacode/shaka/blob/main/skills/shaka/references/migration.md' \
                      '#upgrade-the-configuration-layout'

      include InitializerInput
      include InitializerDestination
      include InitializerReadme

      def initialize(root:, options:)
        @root = root
        @options = options
      end

      def call
        files = generated_files
        RepositoryConfig::ReviewSchema.new(review_policy).validate
        RepositoryConfig::MergeSchema.new(merge_policy).validate
        preflight_destination
        RepositoryConfig::CommandSchema.new(root: @root, layout: LAYOUT).validate_available_optional_commands
        preflight_files(files)
        write_files(files)
        report_legacy_readme
        Configuration.worktree(root: @root)
      end

      private

      def preflight_destination
        verify_git_root!
        preflight_directories
        refuse_legacy_configuration!
      end

      # Generated wrappers resolve the root with Git, so Git must name exactly this directory.
      def verify_git_root!
        environment = GIT_ENVIRONMENT.to_h { |name| [name, nil] }
        output, error, status = Open3.capture3(environment, 'git', '-C', @root, 'rev-parse', '--show-toplevel')
        raise Error, "Cannot identify repository root: #{error.strip}" unless status.success?

        git_root = output.delete_suffix("\n")
        raise Error, "--root must be the Git worktree root: #{git_root}" unless File.realpath(git_root) == @root
      end

      # A repository that already has the old layout, or pieces of it, moves with
      # `seam upgrade`; creating the new layout beside it would leave two configurations.
      def refuse_legacy_configuration!
        if Configuration::Layout.worktree(root: @root, allow_missing: true) == Configuration::Layout::LEGACY
          raise Error, "#{Configuration::Paths::CONTRACT} already exists; run `shaka seam upgrade --root .` " \
                       "to move it to #{LAYOUT.contract} (#{UPGRADE_GUIDE})"
        end
        legacy = legacy_command_entries
        return if legacy.empty?

        raise Error, "#{legacy.join(', ')} belongs to the old layout without #{Configuration::Paths::CONTRACT}; " \
                     "move Shaka commands to #{LAYOUT.command_directory}/ or remove them before seam init"
      end

      def legacy_command_entries
        layout = Configuration::Layout::LEGACY
        [*layout.commands.values, *layout.legacy_optional.values].select do |relative|
          Configuration::Layout.entry?(File.join(@root, relative))
        end
      end

      def generated_files
        wrappers = LAYOUT.required.to_h do |name, relative|
          command = required("#{name}_command").then { |value| command_arguments(value, name) }
          [Configuration::Paths.at(@root, relative), wrapper(command)]
        end
        wrappers.merge(Configuration::Paths.at(@root, LAYOUT.contract) => config_source,
                       Configuration.path(@root, :POINTER) => readme_source(LAYOUT))
      end

      def config_source
        config = config_hash
        Configuration.generated_contract(marker: MARKER, data: config)
      end

      # base_branch is omitted when it was not requested: an absent key means the
      # repository's default branch, so writing one would pin a value nobody chose.
      def config_hash
        {
          'version' => 1,
          'base_branch' => base_branch,
          'review' => review_policy,
          'merge' => merge_policy,
          'branches' => { 'name' => '{login}-{host}/{issue}-{description}' },
          'wip' => RepositoryConfig::DEFAULT_WIP
        }.compact
      end

      def merge_policy
        { 'preference' => @options.fetch(:merge_preference, 'ask'),
          RepositoryConfig::MergeSchema::REQUIRED_CHECKS => @options[:required_checks] }.compact
      end

      def review_policy
        required_policy = required('review_policy')
        names = @options[:ci_review_jobs]
        if required_policy == 'none'
          raise Error, '--ci-review-job must be omitted when review policy is none' if names

          return { 'required' => required_policy }
        end
        raise Error, '--ci-review-job is required' if names.nil? || names.empty?

        { 'required' => required_policy, RepositoryConfig::ReviewSchema::CI_REVIEW_JOBS => names }
      end

      # Matches the wrapper `seam upgrade` produces from the old template, so upgraded
      # and freshly initialized repositories run the same code.
      def wrapper(arguments)
        <<~SHELL
          #!/bin/sh
          # #{MARKER}
          set -eu
          #{Configuration::WrapperTemplate::SHELL_ROOT}
          cd "$root"
          exec #{arguments.shelljoin} "$@"
        SHELL
      end
    end
  end
end
